import os
import tempfile
import unittest
from unittest.mock import patch

from src.processors.summarize import Summarizer, _build_prompt


class TestBuildPrompt(unittest.TestCase):
    def test_labels_the_three_inputs(self):
        p = _build_prompt("AG", "PK", "TX")
        self.assertIn("### MEETING AGENDA\nAG", p)
        self.assertIn("### AGENDA PACKET\nPK", p)
        self.assertIn("### MEETING TRANSCRIPT\nTX", p)

    def test_missing_optional_inputs_are_marked(self):
        p = _build_prompt("", "", "TX")
        self.assertIn("### MEETING AGENDA\n(none provided)", p)
        self.assertIn("### AGENDA PACKET\n(none provided)", p)


class TestProcessForDate(unittest.TestCase):
    def test_reads_sources_builds_prompt_and_writes_summary(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        transcript = os.path.join(tmp.name, "t.txt")
        with open(transcript, "w") as f:
            f.write("TRANSCRIPT BODY")
        out = os.path.join(tmp.name, "s.md")

        s = Summarizer()
        with (
            patch.object(
                s, "construct_filepath_for_date", side_effect=[transcript, out]
            ),
            patch(
                "src.processors.summarize.find_document",
                side_effect=["/a.pdf", "/p.pdf"],
            ),
            patch(
                "src.processors.summarize.pdf_to_text",
                side_effect=["AGENDA TEXT", "PACKET TEXT"],
            ),
            patch(
                "src.processors.summarize.generate", return_value="THE SUMMARY"
            ) as gen,
        ):
            s.process_for_date("2026-10-06 07_00 PM")

        with open(out) as f:
            self.assertEqual(f.read(), "THE SUMMARY")
        prompt = gen.call_args.args[1]
        self.assertIn("### MEETING AGENDA\nAGENDA TEXT", prompt)
        self.assertIn("### AGENDA PACKET\nPACKET TEXT", prompt)
        self.assertIn("### MEETING TRANSCRIPT\nTRANSCRIPT BODY", prompt)

    def test_empty_summary_raises(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        transcript = os.path.join(tmp.name, "t.txt")
        with open(transcript, "w") as f:
            f.write("body")
        s = Summarizer()
        with (
            patch.object(
                s, "construct_filepath_for_date", side_effect=[transcript, "/out.md"]
            ),
            patch("src.processors.summarize.find_document", return_value=None),
            patch("src.processors.summarize.pdf_to_text", return_value=""),
            patch("src.processors.summarize.generate", return_value="   "),
        ):
            with self.assertRaises(Exception):
                s.process_for_date("2026-10-06 07_00 PM")


class TestRecordLegacySummaries(unittest.TestCase):
    def test_flags_summaries_this_stage_did_not_generate(self):
        s = Summarizer()
        with (
            patch.object(s, "gather_dates", return_value=["d1", "d2", "d3"]),
            patch("src.processors.summarize.r") as r,
        ):
            r.hkeys.return_value = [b"d2"]  # only d2 was generated by this stage
            s._record_legacy_summaries()

        r.sadd.assert_called_once()
        args = r.sadd.call_args.args
        self.assertEqual(args[0], "legacy_summary.cc_mtg")
        self.assertEqual(set(args[1:]), {"d1", "d3"})

    def test_no_legacy_means_no_write(self):
        s = Summarizer()
        with (
            patch.object(s, "gather_dates", return_value=["d1"]),
            patch("src.processors.summarize.r") as r,
        ):
            r.hkeys.return_value = [b"d1"]
            s._record_legacy_summaries()
        r.sadd.assert_not_called()


if __name__ == "__main__":
    unittest.main()
